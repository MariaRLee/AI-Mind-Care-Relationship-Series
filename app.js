const state = {
  activeSeries: "all",
  query: ""
};

const refs = {
  tabs: document.getElementById("categoryTabs"),
  catalog: document.getElementById("catalog"),
  search: document.getElementById("searchInput"),
  clearSearch: document.getElementById("clearSearchBtn"),
  summary: document.getElementById("catalogSummary"),
  noResults: document.getElementById("noResults"),
  modal: document.getElementById("episodeModal"),
  modalSeries: document.getElementById("modalSeries"),
  modalEpisode: document.getElementById("modalEpisode"),
  modalTitle: document.getElementById("modalTitle"),
  modalTheme: document.getElementById("modalTheme"),
  modalVideoLink: document.getElementById("modalVideoLink"),
  copyTitleBtn: document.getElementById("copyTitleBtn"),
  randomEpisodeBtn: document.getElementById("randomEpisodeBtn"),
  installBtn: document.getElementById("installBtn")
};

function normalizeEpisode(item) {
  if (typeof item === "string") {
    return {
      title: item,
      videoUrl: "",
      status: "短片規劃"
    };
  }

  return {
    title: item.title || "",
    videoUrl: item.videoUrl || "",
    status: item.status || (item.videoUrl ? "可觀看" : "短片規劃")
  };
}

function getCounts() {
  const seriesCount = relationshipSeries.length;
  const seasons = relationshipSeries.flatMap(series => series.seasons);
  const episodes = seasons.flatMap(season => season.episodes);

  return {
    seriesCount,
    seasonCount: seasons.length,
    episodeCount: episodes.length
  };
}

function setCounts() {
  const counts = getCounts();
  document.getElementById("seriesCount").textContent = counts.seriesCount;
  document.getElementById("seasonCount").textContent = counts.seasonCount;
  document.getElementById("episodeCount").textContent = counts.episodeCount;
}

function buildTabs() {
  const allTab = {
    id: "all",
    shortName: "全部"
  };

  const tabs = [allTab, ...relationshipSeries];

  refs.tabs.innerHTML = tabs.map(tab => `
    <button
      class="category-tab"
      type="button"
      role="tab"
      aria-selected="${state.activeSeries === tab.id}"
      data-series-tab="${tab.id}"
    >
      ${tab.shortName}
    </button>
  `).join("");

  refs.tabs.querySelectorAll("[data-series-tab]").forEach(button => {
    button.addEventListener("click", () => {
      state.activeSeries = button.dataset.seriesTab;
      buildTabs();
      renderCatalog();
    });
  });
}

function matchesQuery(series, season, episode) {
  const query = state.query.trim().toLowerCase();
  if (!query) return true;

  const haystack = [
    series.name,
    series.shortName,
    series.subtitle,
    season.label,
    season.theme,
    episode.title
  ].join(" ").toLowerCase();

  return haystack.includes(query);
}

function filteredSeries() {
  return relationshipSeries
    .filter(series => state.activeSeries === "all" || state.activeSeries === series.id)
    .map(series => {
      const seasons = series.seasons
        .map(season => {
          const episodes = season.episodes
            .map(normalizeEpisode)
            .filter(episode => matchesQuery(series, season, episode));

          return {
            ...season,
            episodes
          };
        })
        .filter(season => season.episodes.length > 0);

      return {
        ...series,
        seasons
      };
    })
    .filter(series => series.seasons.length > 0);
}

function renderCatalog() {
  const seriesList = filteredSeries();
  const visibleEpisodes = seriesList
    .flatMap(series => series.seasons)
    .flatMap(season => season.episodes)
    .length;

  refs.summary.textContent = state.query
    ? `找到 ${visibleEpisodes} 個符合「${state.query}」的短片題目`
    : `目前顯示 ${visibleEpisodes} 個短片題目`;

  refs.clearSearch.hidden = !state.query;
  refs.noResults.hidden = seriesList.length > 0;

  refs.catalog.innerHTML = seriesList.map(series => `
    <section class="series-card" data-series="${series.id}">
      <div class="series-card-head">
        <div class="series-title-wrap">
          <div class="series-icon" aria-hidden="true">${series.icon}</div>
          <div>
            <h3>${series.name}</h3>
            <p class="series-subtitle">${series.subtitle}</p>
          </div>
        </div>
        <div class="series-meta">
          ${series.seasons.length} 季 ·
          ${series.seasons.reduce((sum, season) => sum + season.episodes.length, 0)} 集
        </div>
      </div>

      <div class="seasons">
        ${series.seasons.map((season, seasonIndex) => {
          const shouldOpen =
            Boolean(state.query) ||
            (series.id === "couple" && seasonIndex === 0) ||
            (series.seasons.length === 1);

          return `
            <div class="season-block">
              <button
                class="season-toggle"
                type="button"
                aria-expanded="${shouldOpen}"
                aria-controls="${season.id}-panel"
                data-season-toggle="${season.id}"
              >
                <span class="season-label">
                  <strong>${season.label}｜${season.theme}</strong>
                  <span>${season.episodes.length} 集</span>
                </span>
                <span class="season-chevron" aria-hidden="true">⌄</span>
              </button>

              <div
                class="episode-grid"
                id="${season.id}-panel"
                ${shouldOpen ? "" : "hidden"}
              >
                ${season.episodes.map((episode, index) => `
                  <article class="episode-card">
                    <div>
                      <span class="episode-number">EP ${String(index + 1).padStart(2, "0")}</span>
                      <p class="episode-title">${episode.title}</p>
                    </div>

                    <div class="episode-actions">
                      <span class="episode-status">${episode.status}</span>
                      <button
                        class="episode-open"
                        type="button"
                        data-open-episode
                        data-series-id="${series.id}"
                        data-season-id="${season.id}"
                        data-episode-index="${index}"
                      >
                        開啟
                      </button>
                    </div>
                  </article>
                `).join("")}
              </div>
            </div>
          `;
        }).join("")}
      </div>
    </section>
  `).join("");

  wireCatalogInteractions(seriesList);
}

function wireCatalogInteractions(seriesList) {
  refs.catalog.querySelectorAll("[data-season-toggle]").forEach(button => {
    button.addEventListener("click", () => {
      const panel = document.getElementById(`${button.dataset.seasonToggle}-panel`);
      const expanded = button.getAttribute("aria-expanded") === "true";
      button.setAttribute("aria-expanded", String(!expanded));
      panel.hidden = expanded;
    });
  });

  refs.catalog.querySelectorAll("[data-open-episode]").forEach(button => {
    button.addEventListener("click", () => {
      const series = seriesList.find(item => item.id === button.dataset.seriesId);
      const season = series?.seasons.find(item => item.id === button.dataset.seasonId);
      const episode = season?.episodes[Number(button.dataset.episodeIndex)];

      if (series && season && episode) {
        openEpisodeModal(series, season, episode, Number(button.dataset.episodeIndex));
      }
    });
  });
}

function openEpisodeModal(series, season, episode, episodeIndex) {
  refs.modalSeries.textContent = series.name;
  refs.modalEpisode.textContent = `${season.label} · EP ${String(episodeIndex + 1).padStart(2, "0")}`;
  refs.modalTitle.textContent = episode.title;
  refs.modalTheme.textContent = `本季主題：${season.theme}`;

  if (episode.videoUrl) {
    refs.modalVideoLink.href = episode.videoUrl;
    refs.modalVideoLink.hidden = false;
  } else {
    refs.modalVideoLink.hidden = true;
    refs.modalVideoLink.removeAttribute("href");
  }

  refs.modal.hidden = false;
  document.body.style.overflow = "hidden";
  refs.copyTitleBtn.focus();
}

function closeModal() {
  refs.modal.hidden = true;
  document.body.style.overflow = "";
}

function getAllEpisodeRecords() {
  return relationshipSeries.flatMap(series =>
    series.seasons.flatMap(season =>
      season.episodes.map((episode, index) => ({
        series,
        season,
        episode: normalizeEpisode(episode),
        index
      }))
    )
  );
}

refs.search.addEventListener("input", event => {
  state.query = event.target.value.trim();
  renderCatalog();
});

refs.clearSearch.addEventListener("click", () => {
  state.query = "";
  refs.search.value = "";
  renderCatalog();
  refs.search.focus();
});

refs.modal.querySelectorAll("[data-close-modal]").forEach(element => {
  element.addEventListener("click", closeModal);
});

document.addEventListener("keydown", event => {
  if (event.key === "Escape" && !refs.modal.hidden) {
    closeModal();
  }
});

refs.copyTitleBtn.addEventListener("click", async () => {
  const title = refs.modalTitle.textContent;

  try {
    await navigator.clipboard.writeText(title);
    const original = refs.copyTitleBtn.textContent;
    refs.copyTitleBtn.textContent = "已複製";
    setTimeout(() => {
      refs.copyTitleBtn.textContent = original;
    }, 1200);
  } catch (error) {
    window.prompt("請複製以下題目：", title);
  }
});

refs.randomEpisodeBtn.addEventListener("click", () => {
  const records = getAllEpisodeRecords();
  const pick = records[Math.floor(Math.random() * records.length)];
  openEpisodeModal(pick.series, pick.season, pick.episode, pick.index);
});

let deferredInstallPrompt = null;

window.addEventListener("beforeinstallprompt", event => {
  event.preventDefault();
  deferredInstallPrompt = event;
  refs.installBtn.hidden = false;
});

refs.installBtn.addEventListener("click", async () => {
  if (!deferredInstallPrompt) return;

  deferredInstallPrompt.prompt();
  await deferredInstallPrompt.userChoice;
  deferredInstallPrompt = null;
  refs.installBtn.hidden = true;
});

window.addEventListener("appinstalled", () => {
  refs.installBtn.hidden = true;
});

if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("sw.js").catch(() => {
      // 靜默失敗：不影響一般網頁使用。
    });
  });
}

setCounts();
buildTabs();
renderCatalog();
